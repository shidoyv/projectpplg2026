-- -------------------------------------------------------------
-- 1. TABEL: karya_batik
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.karya_batik (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    user_id UUID DEFAULT NULL,
    nama_kain TEXT NOT NULL,
    filosofi_karya TEXT NOT NULL,
    file_gambar_url TEXT NOT NULL,
    palet_warna JSONB DEFAULT '[]'::jsonb,
    motif TEXT DEFAULT 'Kreasi Bebas',
    pembuat TEXT DEFAULT 'Pengrajin Lelana',
    is_publik BOOLEAN DEFAULT TRUE NOT NULL
);

-- Indeks untuk mempercepat performa kueri galeri pameran
CREATE INDEX IF NOT EXISTS idx_karya_batik_created_at ON public.karya_batik (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_karya_batik_motif ON public.karya_batik (motif);
CREATE INDEX IF NOT EXISTS idx_karya_batik_is_publik ON public.karya_batik (is_publik);

-- -------------------------------------------------------------
-- 2. ROW LEVEL SECURITY (RLS) & HAK AKSES
-- -------------------------------------------------------------
ALTER TABLE public.karya_batik ENABLE ROW LEVEL SECURITY;

-- Kebijakan: Publik dapat melihat semua karya batik yang bersifat publik
DROP POLICY IF EXISTS "Publik dapat melihat karya batik" ON public.karya_batik;
CREATE POLICY "Publik dapat melihat karya batik"
    ON public.karya_batik
    FOR SELECT
    USING (is_publik = TRUE);

-- Kebijakan: Pengunjung dapat menyimpan karya batik baru
DROP POLICY IF EXISTS "Pengunjung dapat menyimpan karya batik baru" ON public.karya_batik;
CREATE POLICY "Pengunjung dapat menyimpan karya batik baru"
    ON public.karya_batik
    FOR INSERT
    WITH CHECK (TRUE);

-- Kebijakan: Pengunjung dapat menghapus karya batik
DROP POLICY IF EXISTS "Pengunjung dapat menghapus karya batik" ON public.karya_batik;
CREATE POLICY "Pengunjung dapat menghapus karya batik"
    ON public.karya_batik
    FOR DELETE
    USING (TRUE);

-- -------------------------------------------------------------
-- 3. SUPABASE STORAGE BUCKET: karya-batik
-- -------------------------------------------------------------
INSERT INTO storage.buckets (id, name, public)
VALUES ('karya-batik', 'karya-batik', TRUE)
ON CONFLICT (id) DO UPDATE SET public = TRUE;

-- Kebijakan Storage: Publik dapat melihat dan mengunduh berkas gambar batik
DROP POLICY IF EXISTS "Public Read Karya Batik Storage" ON storage.objects;
CREATE POLICY "Public Read Karya Batik Storage"
    ON storage.objects
    FOR SELECT
    USING (bucket_id = 'karya-batik');

-- Kebijakan Storage: Publik dapat mengunggah berkas gambar batik baru
DROP POLICY IF EXISTS "Public Upload Karya Batik Storage" ON storage.objects;
CREATE POLICY "Public Upload Karya Batik Storage"
    ON storage.objects
    FOR INSERT
    WITH CHECK (bucket_id = 'karya-batik');

-- Kebijakan Storage: Publik dapat menghapus berkas gambar batik
DROP POLICY IF EXISTS "Public Delete Karya Batik Storage" ON storage.objects;
CREATE POLICY "Public Delete Karya Batik Storage"
    ON storage.objects
    FOR DELETE
    USING (bucket_id = 'karya-batik');
